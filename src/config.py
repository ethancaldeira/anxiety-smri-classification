"""
Configuration for the GSP anxiety MRI classification experiments.
abide/config.py overrides the dataset-specific attributes for the ABIDE arm.
"""

import os
from datetime import datetime


class Config:
    """Configuration for anxiety MRI classification experiments"""
    
    # ==========================================
    # BASE PATHS
    # ==========================================
    
    BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    DATA_DIR = os.path.join(BASE_DIR, 'data')
    
    # ==========================================
    # DATASET SELECTION
    # ==========================================
    
    DATASET = 'GSP'
    
    # GSP subset filtering. USE_GSP_SUBSET=1 (default) restricts the cohort to
    # the 200 subjects in GSP_SUBSET_FILE, which splits/make_gsp_split.py
    # generates; USE_GSP_SUBSET=0 uses every subject with slices and a label.
    USE_GSP_SUBSET = bool(int(os.environ.get('USE_GSP_SUBSET', '1')))
    GSP_SUBSET_FILE = os.path.join(DATA_DIR, 'GSP', 'GSP_subject_list_200.txt')

    # Optional fixed train/val/test split (JSON with train/val/test subject
    # lists), e.g. the anxiety-fmri-classification GSP split for the Ch7 sMRI arm.
    # Subjects not listed are excluded. Default: data/data_split_<dataset>_seed<seed>.json
    SPLIT_FILE = os.environ.get('SPLIT_FILE') or None

    # Sex-stratified runs: 'M' or 'F' restricts the subjects to one sex, with
    # its own subject split (data/data_split_GSP_<sex>_seed<seed>.json).
    SEX_FILTER = os.environ.get('SEX_FILTER') or None
    
    # ==========================================
    # EXPERIMENT SETTINGS
    # ==========================================
    
    # Experiment type: 'raw' or 'preprocessed'
    EXPERIMENT_TYPE = os.environ.get('EXPERIMENT_TYPE', 'raw')

    USE_CLASS_WEIGHTS = True

    # View orientation: 'axial', 'sagittal', 'coronal'
    VIEW_MODE = os.environ.get('VIEW_MODE', 'axial')

    # ---- Pipeline-validation hooks ---------------------------------------
    # LABEL_PERMUTE=1  : subject-level label shuffle (permutation test).
    # TARGET_OVERRIDE  : use a different participants.tsv column as the binary
    #                    target instead of TARGET_COLUMN. Supports:
    #                      Sex            -> F=1, M=0
    #                      Anxiety_Binary -> default (no override)
    # PERMUTE_SEED     : RNG seed for the label shuffle (default 1234).
    LABEL_PERMUTE = bool(int(os.environ.get('LABEL_PERMUTE', '0')))
    TARGET_OVERRIDE = os.environ.get('TARGET_OVERRIDE') or None
    PERMUTE_SEED = int(os.environ.get('PERMUTE_SEED', '1234'))
    
    # ==========================================
    # DATASET-SPECIFIC CONFIGURATION
    # ==========================================
    
    # GSP (adults, ages 18-35)
    PARTICIPANTS_FILE = os.path.join(DATA_DIR, 'GSP', 'GSP_participants.tsv')
    TARGET_COLUMN = 'Anxiety_Binary'  # Binary label, computed from STAI_tAnxiety ≥ STAI_CUTOFF
    SUBJECT_ID_COLUMN = 'participant_id'
    # Binary cutoff applied to the continuous STAI_tAnxiety score. Default
    # is 36, the median of the full GSP cohort (N=879), which gives a
    # near-balanced binary task (104:96 in the 200-subject subset). The
    # conventional clinical cutoff of 40 is contested (Knight 1983;
    # Julian 2011; an ROC study found optimal cutoff = 44). data_loader
    # recomputes Anxiety_Binary from STAI_tAnxiety using this value,
    # overriding any precomputed column in the participants TSV. The
    # subset and split generated by splits/make_gsp_split.py are stratified
    # at this cutoff.
    STAI_CUTOFF = int(os.environ.get('STAI_CUTOFF', '36'))
    BASE_SLICES_DIR = os.path.join(DATA_DIR, 'GSP', 'slices', EXPERIMENT_TYPE)
    SLICES_DIR = os.path.join(BASE_SLICES_DIR, VIEW_MODE)

    MODEL_INPUT_SIZE = (224, 224)  # slices are resized to this on load
    
    # ==========================================
    # DATA SPLIT
    # ==========================================
    TRAIN_SPLIT = 0.65
    VAL_SPLIT = 0.15
    TEST_SPLIT = 0.2
    RANDOM_SEED = 42                # subject splits and k-fold assignment
    TRAIN_SEED = int(os.environ.get('TRAIN_SEED', '42'))  # weight init, shuffling, dropout
    DETERMINISTIC_OPS = bool(int(os.environ.get('DETERMINISTIC_OPS', '0')))  # bit-identical GPU runs, ~5x slower
    # ==========================================
    # CROSS-VALIDATION
    # ==========================================
    
    USE_KFOLD = bool(int(os.environ.get('USE_KFOLD', '0')))  # Set to True (or 1) for k-fold CV
    N_FOLDS = int(os.environ.get('N_FOLDS', '5'))
    
    # ==========================================
    # TRAINING PARAMETERS
    # ==========================================

    BATCH_SIZE = 16
    EPOCHS = 50                     # total budget (stage 1 + stage 2 combined)
    LEARNING_RATE = 1e-4            # stage-2 peak LR (all layers)
    EARLY_STOPPING_PATIENCE = 10    # stage 2 only, on val_loss

    # Two-stage fine-tuning: first warm the head with the backbone frozen,
    # then unfreeze everything for joint fine-tuning.
    STAGE1_EPOCHS = 10              # head only, backbone frozen, fixed LR
    STAGE1_LR = float(os.environ.get('STAGE1_LR', '1e-4'))  # stage-1 LR (head only)

    # LR schedule for stage 2: linear warmup → cosine decay to MIN_LR.
    WARMUP_EPOCHS = 10
    MIN_LR = 1e-7

    # MRI-appropriate augmentation (training only) via TorchIO
    # (Pérez-García et al. 2021, doi: 10.1016/j.cmpb.2021.106236). Knobs
    # below feed src/mri_augment.make_train_transform. RandomFlip is along
    # the LR axis only; there is no flip along the superior/inferior or
    # anterior/posterior axes.
    #
    # Off by default, and off in all reported runs: in the sex-classification
    # pipeline check on the 200-subject GSP subset it degraded calibration
    # (predicted probabilities shifted low, so thresholded accuracy fell while
    # AUC stayed high). USE_AUGMENTATION=1 enables it.
    USE_AUGMENTATION = bool(int(os.environ.get('USE_AUGMENTATION', '0')))
    AUG_FLIP_PROB     = 0.5         # LR-axis only
    AUG_DEGREES       = 5           # ±5° rotation
    AUG_SCALE         = 0.05        # ±5% zoom
    AUG_TRANSLATE_PX  = 5           # ±5px translation
    AUG_BIAS_COEFF    = 0.3         # RandomBiasField smoothness
    AUG_BIAS_ORDER    = 3
    AUG_LOG_GAMMA     = 0.1         # RandomGamma log-gamma range
    AUG_NOISE_STD     = 0.03        # Rician proxy upper bound

    # ==========================================
    # MODEL ARCHITECTURE
    # ==========================================

    # Transfer learning source. Default is ImageNet with the backbone's own
    # preprocess_input; RadImageNet inputs are scaled by /255 (see
    # data_loader._get_preprocess_input). An independent replication
    # (TMLR 2023) found ImageNet ≥ RadImageNet for downstream medical tasks.
    USE_RADIMAGENET = bool(int(os.environ.get('USE_RADIMAGENET', '0')))

    # Base model: 'ResNet50', 'DenseNet121', 'InceptionV3', 'VGG16', 'VGG19'
    BASE_MODEL = os.environ.get('BASE_MODEL', 'ResNet50')

    # RadImageNet no-top weights (only if USE_RADIMAGENET = True), read from
    # RADIMAGENET_DIR (default: pretrained_weights/radimagenet/).
    RADIMAGENET_DIR = os.environ.get(
        'RADIMAGENET_DIR', os.path.join(BASE_DIR, 'pretrained_weights', 'radimagenet'))
    RADIMAGENET_WEIGHTS_MAP = {
        'ResNet50': os.path.join(RADIMAGENET_DIR, 'RadImageNet-ResNet50_notop.h5'),
        'DenseNet121': os.path.join(RADIMAGENET_DIR, 'RadImageNet-DenseNet121_notop.h5'),
        'InceptionV3': os.path.join(RADIMAGENET_DIR, 'RadImageNet-InceptionV3_notop.h5'),
    }
    RADIMAGENET_WEIGHTS_PATH = RADIMAGENET_WEIGHTS_MAP.get(BASE_MODEL) if USE_RADIMAGENET else None

    # Stage 1 freezes the backbone, stage 2 unfreezes — this attribute is
    # only used as the *initial* setting; train.py flips it for stage 2.
    FREEZE_BASE = False
    DENSE_LAYERS = [256]
    DROPOUT_RATE = 0.5
    ACTIVATION = 'relu'
    
    # ==========================================
    # SLICE SELECTION
    # ==========================================
    
    USE_CENTRAL_SLICES = True  # Select only central slices
    N_CENTRAL_SLICES = 40  # Number of slices per subject
    
    # ==========================================
    # OUTPUT
    # ==========================================
    
    NUM_CLASSES = 1  # Binary classification
    
    # Experiment naming
    TIMESTAMP = datetime.now().strftime('%Y%m%d_%H%M%S')
    dataset_label = f"GSP{'_subset' if USE_GSP_SUBSET else ''}"

    EXPERIMENT_NAME = os.environ.get(
        'EXPERIMENT_NAME',
        f"{EXPERIMENT_TYPE}_{VIEW_MODE}_{dataset_label}_{BASE_MODEL}_{TIMESTAMP}",
    )

    # Single canonical output layout — one dir per experiment.
    #   results/<EXPERIMENT_NAME>/
    #     ├── config.json
    #     ├── predictions_slice.csv
    #     ├── metrics_slice.json
    #     ├── metrics_subject.json
    #     ├── training_history.json
    #     └── plots/
    # Directories are created on demand by train.py, not at import time.
    RESULTS_ROOT = os.path.join(BASE_DIR, 'results')
    RUN_DIR = os.path.join(RESULTS_ROOT, EXPERIMENT_NAME)
    PLOTS_DIR = os.path.join(RUN_DIR, 'plots')

    @classmethod
    def make_run_dirs(cls):
        """Create the per-run directory tree. Call from train.py."""
        os.makedirs(cls.RUN_DIR, exist_ok=True)
        os.makedirs(cls.PLOTS_DIR, exist_ok=True)
    
    @classmethod
    def print_config(cls):
        """Print current configuration"""
        print("=" * 60)
        print(f"EXPERIMENT: {cls.EXPERIMENT_NAME}")
        print("=" * 60)
        
        # Dataset info
        print(f"\nDATASET:")
        print(f"  Name: {cls.DATASET}")
        if cls.DATASET == 'GSP':
            print(f"  Target: {cls.TARGET_COLUMN} (STAI-T ≥ {cls.STAI_CUTOFF})")
            if cls.USE_GSP_SUBSET:
                print(f"  Subset: 200 subjects (from {cls.GSP_SUBSET_FILE})")
            else:
                print(f"  Subjects: all with slices and a label")
            if cls.SEX_FILTER:
                print(f"  Sex filter: {cls.SEX_FILTER} only")
        else:
            print(f"  Target: {cls.TARGET_COLUMN}")
        if cls.SPLIT_FILE:
            print(f"  Split file: {cls.SPLIT_FILE}")

        print(f"  Participants file: {cls.PARTICIPANTS_FILE}")
        
        # Data settings
        print(f"\nDATA:")
        print(f"  Experiment type: {cls.EXPERIMENT_TYPE}")
        
        print(f"  View mode: {cls.VIEW_MODE}")
        print(f"  Slices directory: {cls.SLICES_DIR}")
        print(f"  Model input size: {cls.MODEL_INPUT_SIZE}")
        
        if cls.USE_CENTRAL_SLICES:
            print(f"  Slice selection: {cls.N_CENTRAL_SLICES} central slices per subject")
        else:
            print(f"  Slice selection: All slices")
        
        # Model settings
        print(f"\nMODEL:")
        print(f"  Base: {cls.BASE_MODEL}")
        print(f"  Weights: {'RadImageNet (medical)' if cls.USE_RADIMAGENET else 'ImageNet (natural)'}")
        if cls.USE_RADIMAGENET and cls.RADIMAGENET_WEIGHTS_PATH:
            print(f"  Weights file: {cls.RADIMAGENET_WEIGHTS_PATH}")
        print(f"  Freeze base: {cls.FREEZE_BASE}")
        print(f"  Dense layers: {cls.DENSE_LAYERS}")
        print(f"  Dropout: {cls.DROPOUT_RATE}")
        
        # Training settings
        print(f"\nTRAINING:")
        print(f"  Batch size: {cls.BATCH_SIZE}")
        print(f"  Epochs: {cls.EPOCHS}")
        print(f"  Learning rate: {cls.LEARNING_RATE}")
        print(f"  Early stopping patience: {cls.EARLY_STOPPING_PATIENCE}")
        print(f"  Class weights: {cls.USE_CLASS_WEIGHTS}")
        
        if cls.USE_KFOLD:
            print(f"  Cross-validation: {cls.N_FOLDS}-fold")
        else:
            print(f"  Split: {cls.TRAIN_SPLIT}/{cls.VAL_SPLIT}/{cls.TEST_SPLIT} (train/val/test)")
        
        # Output
        print(f"\nOUTPUT:")
        print(f"  Results: {cls.RUN_DIR}")
        print("=" * 60)


if __name__ == '__main__':
    Config.print_config()
